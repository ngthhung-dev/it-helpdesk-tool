public static class LegacyVnEncoding
{
    public enum Kind { None, Tcvn3, Vni }

    /// <summary>Đoán bảng mã theo tên họ font.</summary>
    public static Kind Detect(string family) =>
        family.StartsWith(".Vn", StringComparison.OrdinalIgnoreCase) ? Kind.Tcvn3 :
        family.StartsWith("VNI", StringComparison.OrdinalIgnoreCase) || family.StartsWith("VN-", StringComparison.OrdinalIgnoreCase) ? Kind.Vni :
        Kind.None;

    /// <summary>Font TCVN3 họ “…H” (.VnTimeH) chỉ có chữ hoa: vẽ chữ hoa ở vị trí mã chữ thường.</summary>
    public static bool IsTcvn3Upper(string family) =>
        family.StartsWith(".Vn", StringComparison.OrdinalIgnoreCase) && family.Split(' ')[0].EndsWith('H');

    public static string Convert(string text, string family)
    {
        var kind = Detect(family);
        if (kind == Kind.None) return text;
        if (kind == Kind.Tcvn3 && IsTcvn3Upper(family)) text = text.ToLowerInvariant();
        var map = kind == Kind.Tcvn3 ? Tcvn3 : Vni;
        var sb = new System.Text.StringBuilder(text.Length * 2);
        // Font mã cũ không có dấu câu Unicode → đổi sang ký tự ASCII tương đương
        text = text.Replace('\u2014', '-').Replace('\u2013', '-').Replace('\u201C', '"').Replace('\u201D', '"')
                   .Replace('\u2018', '\'').Replace('\u2019', '\'').Replace("\u2026", "...");
        foreach (var ch in text.Normalize(System.Text.NormalizationForm.FormC))
        {
            if (map.TryGetValue(ch, out var s)) sb.Append(s);
            // Bảng TCVN3 thiếu chữ hoa có dấu → dùng chữ thường có dấu
            else if (kind == Kind.Tcvn3 && char.IsUpper(ch) && map.TryGetValue(char.ToLowerInvariant(ch), out var lower)) sb.Append(lower);
            else sb.Append(ch);
        }
        return sb.ToString();
    }

